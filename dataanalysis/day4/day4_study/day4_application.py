# 주제: A~F 성적 등급 판정기
#
# [목표]
# 입력한 점수의 구간에 따라 A, B, C, D, F 등급을 판정합니다.
#
# [요구사항]
# 점수를 정수로 입력받습니다.
# 점수가 0보다 작거나 100보다 크면 "입력 오류"를 출력합니다.
# 정상 범위에서는 다음 규칙으로 등급을 판정합니다.
# 90~100: A
# 80~89: B
# 70~79: C
# 60~69: D
# 0~59: F
# if / elif / else를 사용합니다.
# 높은 기준부터 조건을 검사합니다.
# 최종 출력 형식은 아래와 같이 작성합니다.

score = int(input('성적(0~100): '))
attendance = int(input('출석률(0~100): '))

if score < 0 or score > 100: # 성적에 대한 범위 체크
    print('입력 오류: 성적은 0~100 사이여야 합니다')
elif attendance < 0 or attendance > 100:
    print('입력 오류: 출석률은 0 ~ 100 사이여야 합니다')
else:#입력 값들이 범위 내에 있다
    if score >= 90:
        grade = 'A'
    elif score >= 80:
        grade = 'B'
    elif score >= 70:
        grade = 'C'
    elif score >= 60:
        grade = 'D'
    else:
        grade = 'F'
    print(f'정수 : {score}')
    print(f'등급 :{grade}')
# 점수: 85
# 등급: B

