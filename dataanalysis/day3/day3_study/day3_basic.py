# 주제: 기본 주문 금액 계산기
# 권장 시간: 35~45분
#
# [학습 목표]
# input()으로 값을 입력받을 수 있다.
# int()로 숫자 입력을 변환할 수 있다.
# 산술 연산으로 주문금액을 계산할 수 있다.
# f-string으로 결과를 보기 좋게 출력할 수 있다.
#
# [과제]
# 콘솔에서 아래 정보를 입력받아 주문금액을 계산하는 프로그램을 작성하세요.
#
# 입력 항목
# 상품명
# 상품 단가
# 구매 수량
#
# 계산
# 주문금액 = 상품 단가 × 구매 수량
#
# 출력 예시
# 상품명: 무선 키보드
# 단가: 45,000원
# 수량: 2개
# 주문금액: 90,000원

product = input('상품명을 입력 하세요 : ') # 상품명
price = int(input('입력한 상품의 단가를 입력하세요 : ')) #단가)
amount = int(input('구매할 수량을 입력하세요 : ')) #구매수량

#calculate
total_price = price * amount # 총가격

#출력
print(f'상품명 : {product} \n 단가 : {price:,}원 \n 수량: {amount}개 \n 주문 금액: {total_price:,}원')


# [필수 조건]
# 상품명은 input()으로 입력받습니다.
# 단가와 수량은 int()로 형변환합니다.
# 주문금액은 별도 변수에 저장합니다.
# 금액에는 천 단위 쉼표를 적용합니다.
# 주요 코드 줄에 한글 주석을 5개 이상 작성합니다.
